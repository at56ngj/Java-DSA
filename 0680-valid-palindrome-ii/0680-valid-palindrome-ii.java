class Solution {
    public boolean validPalindrome(String s) {
        int left = 0;
        int right = s.length() - 1;
        while (left < right) {
            if (s.charAt(left) != s.charAt(right)) {
                if (isPal(s, left + 1, right)) {
                    return true;
                }
                if (isPal(s, left, right - 1)) {
                    return true;
                }
                return false;
            }
            left++;
            right--;
        }
        return true;
    }

    public boolean isPal(String s, int left, int right) {
        while (left < right) {
            if (s.charAt(left) != s.charAt(right)) {
                return false;
            }
            left++;
            right--;
        }
        return true;
    }
}

